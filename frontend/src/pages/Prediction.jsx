import { useLocation, useNavigate } from "react-router-dom";
import "./Prediction.css";

const TUMOR_INFO = {
  glioma: {
    label: "Glioma",
    color: "#dc2626",
    description:
      "A tumor arising from glial cells in the brain or spinal cord. Gliomas vary widely in severity (grade I-IV) and location.",
    physicianNotes: [
      "Grade and extent typically confirmed via contrast-enhanced MRI or CT",
      "Often referred to neurosurgery or neuro-oncology",
      "Biopsy may be used for histological and molecular grading",
      "Treatment options vary by grade: surgery, radiotherapy, chemotherapy"
    ]
  },
  meningioma: {
    label: "Meningioma",
    color: "#d97706",
    description:
      "A tumor forming in the meninges, the membranes surrounding the brain and spinal cord. Most are benign and slow-growing.",
    physicianNotes: [
      "Growth rate often monitored via follow-up imaging",
      "Neurosurgical referral typical if symptomatic or enlarging",
      "Small, asymptomatic cases may be managed with active surveillance",
      "Surgical resection or stereotactic radiosurgery considered for larger cases"
    ]
  },
  notumor: {
    label: "No Tumor",
    color: "#16a34a",
    description:
      "No tumor pattern was detected in this scan by the model.",
    physicianNotes: [
      "No tumor-related referral indicated based on this result alone",
      "Clinical correlation with patient symptoms is still recommended",
      "Re-scan may be advised if symptoms persist or worsen"
    ]
  },
  pituitary: {
    label: "Pituitary Tumor",
    color: "#7c3aed",
    description:
      "A tumor located in the pituitary gland, which can affect hormone regulation depending on size and type.",
    physicianNotes: [
      "Endocrinology referral often needed to assess hormonal function",
      "Hormone panel (prolactin, GH, ACTH, TSH, etc.) commonly ordered",
      "Neurosurgical referral considered if visual field involvement or mass effect present",
      "Pituitary-protocol MRI often used for detailed characterization"
    ]
  }
};

function normalizeTumorKey(tumor) {
  if (!tumor) return "notumor";
  return tumor.toLowerCase().replace(/\s/g, "");
}

function Prediction() {
  const navigate = useNavigate();
  const location = useLocation();

  const { result, imagePreview } = location.state || {};

  if (!result) {
    return (
      <div className="prediction-page">
        <div className="prediction-card">
          <h1>No Result Found</h1>
          <p>Please upload an MRI scan first.</p>
          <button className="primary-btn" onClick={() => navigate("/upload")}>
            Go to Upload
          </button>
        </div>
      </div>
    );
  }

  const key = normalizeTumorKey(result.tumor);
  const info = TUMOR_INFO[key] || TUMOR_INFO.notumor;
  const confidence = result.confidence ?? 0;

  return (
    <div className="prediction-page">
      <div className="prediction-card">
        <h1>AI Classification Report</h1>

        {imagePreview && (
          <img src={imagePreview} alt="Analyzed MRI" className="result-img" />
        )}

        <div
          className="result-badge"
          style={{ background: info.color + "22", color: info.color }}
        >
          {info.label}
        </div>

        <div className="confidence-bar-wrap">
          <div className="confidence-label">
            <span>Model Confidence</span>
            <span>{confidence}%</span>
          </div>
          <div className="confidence-bar-bg">
            <div
              className="confidence-bar-fill"
              style={{
                width: `${confidence}%`,
                background: info.color,
              }}
            />
          </div>
        </div>

        <p className="result-note">{info.description}</p>

        <div className="next-steps">
          <h3>For Physician Review</h3>
          <ul>
            {info.physicianNotes.map((note, index) => (
              <li key={index}>{note}</li>
            ))}
          </ul>
        </div>

        <div className="prediction-disclaimer">
          <strong>Important:</strong> This report is generated by an AI
          model for laboratory use and is intended to assist, not replace,
          the treating physician. Final diagnosis and treatment decisions
          must be made by a qualified physician after independent review.
        </div>

        <div className="prediction-actions">
          <button className="secondary-btn" onClick={() => navigate("/upload")}>
            Analyze Another Scan
          </button>
          <button className="primary-btn" onClick={() => navigate("/doctors")}>
            Route to Physician
          </button>
        </div>
      </div>
    </div>
  );
}

export default Prediction;
